"""Generate documentation and exports from the same four runs as the demo."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def percent(n):
    return "N/A" if n is None else f"{n:.1%}"


def table(lab):
    lines = ["| Rule | Alerts | Customer precision | Customer recall | Alert precision proxy | Alert recall |",
             "| --- | ---: | ---: | ---: | ---: | --- |"]
    for m in lab["metrics"]:
        c, a = m["customer_level"], m["alert_level"]
        lines.append(f"| {m['rule_id']} | {a['alerts']} | {c['true_positives']}/{c['customers_alerted']} ({percent(c['precision'])}) "
                     f"| {c['true_positives']}/{c['seeded_customers']} ({percent(c['recall'])}) "
                     f"| {a['label_positive_alerts']}/{a['alerts']} ({percent(a['precision'])}) | N/A |")
    return "\n".join(lines)


METRIC_NOTE = """Customer precision = correctly flagged customer–typology pairs / all flagged pairs for that rule.
Customer recall = correctly flagged pairs / all authored positive pairs for that rule.
Alert precision proxy = alerts on customers labeled for that rule / all alerts from that rule.
Repeated alerts count repeatedly in the alert denominator, but once per customer in the customer denominator.
Alert recall is unavailable: there is no exhaustive event-level reference set or count of missed events.
A zero denominator is N/A, not 0% or 100%. All labels express fictional review-worthiness, not confirmed crime.
Cross-rule counts can overlap; do not add customer counts to estimate distinct cases."""


def write_reports(runs):
    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    out = ROOT / "dist" / "data"
    with (out / "metrics.csv").open("w", newline="") as fh:
        fields = ["dataset", "control", "rule_id", "customer_tp", "customer_fp", "customer_fn",
                  "customers_alerted", "seeded_customers", "customer_precision", "customer_recall",
                  "alerts", "label_positive_alerts", "label_negative_alerts", "alert_precision_proxy",
                  "alert_recall", "alert_recall_denominator", "alert_label_basis"]
        writer = csv.DictWriter(fh, fieldnames=fields)
        writer.writeheader()
        for (dataset, control), lab in runs.items():
            for m in lab["metrics"]:
                c, a = m["customer_level"], m["alert_level"]
                writer.writerow(dict(zip(fields, [dataset, control, m["rule_id"], c["true_positives"],
                    c["false_positives"], c["false_negatives"], c["customers_alerted"], c["seeded_customers"],
                    c["precision"], c["recall"], a["alerts"], a["label_positive_alerts"], a["label_negative_alerts"],
                    a["precision"], None, None, a["label_basis"]])))

    baseline, evaluation = runs["baseline", "baseline"], runs["evaluation", "baseline"]
    r03 = baseline["metrics"][2]
    cm, am = r03["customer_level"], r03["alert_level"]
    example = (f"\n\nR03 produces {am['alerts']} alerts across {cm['customers_alerted']} customers. "
               f"Customer precision is {cm['true_positives']}/{cm['customers_alerted']} "
               f"({percent(cm['precision'])}); alert precision proxy is {am['label_positive_alerts']}/{am['alerts']} "
               f"({percent(am['precision'])}). The benign OTC desk contributes "
               f"{sum(a['rule_id'] == 'R03' and a['customer_id'] == c['customer_id'] for a in baseline['alerts'] for c in baseline['customers'] if c['segment'] == 'otc_desk')} repeat alerts.")
    section = ("## Measured results\n\n### Original baseline fixtures\n\n" + table(baseline) + example
               + "\n\n### Separate challenge evaluation\n\n" + table(evaluation) + "\n\n" + METRIC_NOTE
               + "\n\nGenerated by `python3 src/build_lab.py`. Full configurations and results: "
                 "[`metrics.csv`](dist/data/metrics.csv). [Control-tuning case study](docs/control-tuning.md).\n")
    readme = ROOT / "README.md"
    text = readme.read_text()
    start, end = "<!-- results:start -->", "<!-- results:end -->"
    before, rest = text.split(start, 1)
    _, after = rest.split(end, 1)
    readme.write_text(before + start + "\n" + section + end + after)

    lines = ["# Control-tuning case study", "", "Generated from the committed snapshot and four actual runs. "
             "This is a rejected what-if, not a production recommendation.", "", "## Decision and fixed proposal", "",
             "Baseline R03: deposit ≥ $1,000, ≥80% withdrawn within 60 minutes. Proposed: raise only the deposit "
             "floor to $50,000. This round-number materiality hypothesis is declared in code before the evaluation "
             "runs. It tests whether a smaller queue would conceal smaller review-worthy transfers. No thresholds "
             "are selected by searching evaluation labels. There is no automated tuning or training.", "",
             "The original fixture is an explanatory baseline. The separate challenge set was authored with knowledge "
             "of the rules and includes misses, overlaps, benign settlements and threshold edges. It is not a blind "
             "holdout, and neither set establishes production accuracy.", ""]
    for dataset in ("baseline", "evaluation"):
        lines.extend([f"## {dataset.title()} fixtures: R03", "",
                      "| Control | Customer precision | Customer recall | Alert precision proxy | Alerts | Missed customers |",
                      "| --- | ---: | ---: | ---: | ---: | --- |"])
        for control in ("baseline", "proposed"):
            m = next(m for m in runs[dataset, control]["metrics"] if m["rule_id"] == "R03")
            c, a = m["customer_level"], m["alert_level"]
            lines.append(f"| {control} | {c['true_positives']}/{c['customers_alerted']} ({percent(c['precision'])}) "
                         f"| {c['true_positives']}/{c['seeded_customers']} ({percent(c['recall'])}) "
                         f"| {a['label_positive_alerts']}/{a['alerts']} ({percent(a['precision'])}) "
                         f"| {a['alerts']} | {', '.join(m['missed_customers']) or 'None'} |")
        lines.extend(["", "### Workload assumptions", "",
                      "Each dataset covers a fictional 30-day observation period. Illustrative handling assumptions: "
                      "20 minutes per R03 alert, or alternatively 45 minutes per distinct R03 customer case if alerts "
                      "are consolidated. These are separate operating models, not additive, and exclude QC, sanctions "
                      "specialists, information requests and rework. No FTE or real savings claim is made.", ""])
        for control in ("baseline", "proposed"):
            m = next(m for m in runs[dataset, control]["metrics"] if m["rule_id"] == "R03")
            alerts, cases = m["alert_level"]["alerts"], m["customer_level"]["customers_alerted"]
            lines.append(f"- {control.title()}: {alerts} × 20 = {alerts * 20} minutes "
                         f"({alerts * 20 / 60:.2f} hours) per-alert review; alternatively {cases} × 45 = "
                         f"{cases * 45} minutes ({cases * 45 / 60:.2f} hours) consolidated review.")
        lines.append("")
    lines.extend(["## Recommendation, approval and rollback", "",
                  "Do not approve the deposit-floor increase on this evidence: it removes review-worthy customers "
                  "while high-value benign OTC settlement still alerts. Investigate case consolidation and documented "
                  "customer context instead of blanket OTC exemptions; the evaluation includes review-worthy OTC activity.", "",
                  "Before any production change: the monitoring owner, BSA/AML compliance and independent validation/QC "
                  "must agree scope, representative adjudicated data, risk acceptance and acceptance criteria. Engineering "
                  "must reconcile input volumes and implement versioned configuration with an approved release record. "
                  "These are proposed governance requirements, not approvals already obtained.", "",
                  "Pilot in shadow mode. Monitor alert volume and distinct cases by segment, amount and rule; sample "
                  "suppressed activity with independent review; track complaints, escalations, SAR outcomes, data freshness "
                  "and below-threshold activity. Define quantitative tolerances with the owners before launch. Any confirmed "
                  "material miss, data defect or unapproved risk change pauses the pilot. Restore the previous $1,000 "
                  "configuration, re-run the affected observation window and reconcile/review the suppressed queue. "
                  "Do not remove existing cases or bypass direct sanctions controls.", "", "## Metric definitions", "", METRIC_NOTE])
    (docs / "control-tuning.md").write_text("\n".join(lines) + "\n")

    otc = next(c for c in baseline["customers"] if c["segment"] == "otc_desk")
    alert = next(a for a in baseline["alerts"] if a["customer_id"] == otc["customer_id"] and a["rule_id"] == "R03")
    e = alert["evidence"]
    otc_alert_count = sum(a["customer_id"] == otc["customer_id"] and a["rule_id"] == "R03" for a in baseline["alerts"])
    script = f"""# 90-second walkthrough: ready to record

No video or synthesized voice is included. Approximate timings assume a natural speaking pace.
Use the baseline dataset and baseline control. This script and the numbers below are generated from that run.

| Time | Screen action | Suggested narration |
| --- | --- | --- |
| 0–15s | Open the queue. Filter R03. Select {alert['alert_id']} / {otc['customer_id']}. | This lab combines fictional exchange activity with a saved public sanctions and blockchain snapshot. I’ll review a pass-through alert without treating the pattern as proof of crime. |
| 15–35s | Show evidence and customer activity. | The fictional customer deposited ${e['deposit_usd']:,.2f} and withdrew ${e['withdrawn_usd']:,.2f} within {e['minutes_to_last_withdrawal']} minutes. The rule flags timing and amount. It does not prove the withdrawal contains those same funds. |
| 35–50s | Show the OTC segment and expected monthly activity. | An innocent explanation is normal OTC settlement. The fixture describes this activity as documented at onboarding. In a real review I would verify the profile, settlement records and source of funds rather than rely on the segment alone. |
| 50–65s | Choose Request information. Enter rationale. Download case summary. | I would request the supporting records and document what could change my conclusion. With verified settlement evidence, closure may be justified. Missing or inconsistent evidence would support escalation. The download preserves the reasoning. |
| 65–90s | Show metric denominators. Switch to the evaluation set. | Customer precision and alert precision answer different questions. The baseline OTC customer creates {otc_alert_count} repeat alerts. The challenge set also contains review-worthy OTC activity and missed cases. Labels are fictional review priorities. Alert recall is unavailable without exhaustive event labels. These results are test evidence, not production accuracy. |

Suggested caption track: use the narration column as subtitles after recording. Do not display real customer information.
"""
    (docs / "walkthrough.md").write_text(script)
